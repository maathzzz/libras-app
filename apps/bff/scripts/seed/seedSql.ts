import type { SeedContent } from './content';

export const SEED_FILE = new URL('../../../../supabase/seed.sql', import.meta.url);

const literal = (value: string) => `'${value.replaceAll("'", "''")}'`;
const nullableLiteral = (value: string | null) => (value === null ? 'null' : literal(value));
const textArray = (values: readonly string[]) => `array[${values.map(literal).join(', ')}]`;
const jsonb = (value: unknown) => `${literal(JSON.stringify(value))}::jsonb`;

function upsert(
  table: string,
  columns: readonly string[],
  rows: readonly string[][],
  conflict: string,
): string {
  const values = rows.map((row) => `  (${row.join(', ')})`).join(',\n');
  return `insert into app.${table} (${columns.join(', ')}) values\n${values}\n${conflict};`;
}

const updateAll = (columns: readonly string[]) =>
  `on conflict (id) do update set\n  ${columns.map((c) => `${c} = excluded.${c}`).join(',\n  ')}`;

// The remote project is never reset, so the seed must run again on a database that already
// has it: rows are upserted by id. Content removed from here is not deleted from the database.
export function renderSeedSql(content: SeedContent): string {
  const { course, units, lessons, signs, exercises, studyGroups, studies } = content;
  const exerciseIds = exercises.map(({ payload }) => literal(payload.id)).join(', ');

  return `-- Generated by apps/bff/scripts/seed/generateSeed.ts. Do not edit by hand:
-- change scripts/seed/content.ts and run \`pnpm --filter bff db:seed:generate\`.

${upsert(
  'courses',
  ['id', 'title', 'position'],
  [[literal(course.id), literal(course.title), String(course.position)]],
  updateAll(['title', 'position']),
)}

${upsert(
  'units',
  ['id', 'course_id', 'title', 'position'],
  units.map((unit) => [
    literal(unit.id),
    literal(unit.courseId),
    literal(unit.title),
    String(unit.position),
  ]),
  updateAll(['course_id', 'title', 'position']),
)}

${upsert(
  'lessons',
  ['id', 'unit_id', 'title', 'position'],
  lessons.map((lesson) => [
    literal(lesson.id),
    literal(lesson.unitId),
    literal(lesson.title),
    String(lesson.position),
  ]),
  updateAll(['unit_id', 'title', 'position']),
)}

${upsert(
  'signs',
  ['id', 'label', 'image_paths', 'alt', 'description'],
  signs.map((sign) => [
    literal(sign.id),
    literal(sign.label),
    textArray(sign.imagePaths),
    literal(sign.alt),
    nullableLiteral(sign.description),
  ]),
  updateAll(['label', 'image_paths', 'alt', 'description']),
)}

${upsert(
  'exercises',
  ['id', 'lesson_id', 'type', 'position', 'payload'],
  exercises.map(({ lessonId, position, payload }) => [
    literal(payload.id),
    literal(lessonId),
    literal(payload.type),
    String(position),
    jsonb(payload),
  ]),
  updateAll(['lesson_id', 'type', 'position', 'payload']),
)}

-- Rebuilt from scratch: an exercise whose options changed must not keep the old signs.
delete from app.exercise_signs where exercise_id in (${exerciseIds});

${upsert(
  'exercise_signs',
  ['exercise_id', 'sign_id'],
  exercises.flatMap(({ payload, signIds }) =>
    signIds.map((signId) => [literal(payload.id), literal(signId)]),
  ),
  'on conflict do nothing',
)}

${upsert(
  'study_groups',
  ['id', 'title', 'position'],
  studyGroups.map((group) => [literal(group.id), literal(group.title), String(group.position)]),
  updateAll(['title', 'position']),
)}

${upsert(
  'studies',
  ['id', 'group_id', 'position', 'title', 'description', 'pages'],
  studies.map((study) => [
    literal(study.id),
    literal(study.groupId),
    String(study.position),
    literal(study.title),
    literal(study.description),
    jsonb(study.pages),
  ]),
  updateAll(['group_id', 'position', 'title', 'description', 'pages']),
)}

${DRAFT_COPY_SQL}`;
}

// The CMS edits a draft copy of the content (app.draft_*) and, once it exists, the draft
// belongs to the operators: a later seed must not bring back what they deleted or undo what
// they changed. So the draft is filled from the published content only while it is empty,
// as in a fresh environment.
const DRAFT_COPY_SQL = `-- CMS draft: filled from the published content only while it is empty.
do $$
begin
  if exists (select 1 from app.draft_courses) or exists (select 1 from app.draft_signs) then
    return;
  end if;

  insert into app.draft_courses (id, title, position)
  select id, title, position from app.courses;

  insert into app.draft_units (id, course_id, title, position)
  select id, course_id, title, position from app.units;

  insert into app.draft_lessons (id, unit_id, title, position)
  select id, unit_id, title, position from app.lessons;

  insert into app.draft_exercises (id, lesson_id, type, position, payload)
  select id, lesson_id, type, position, payload from app.exercises;

  insert into app.draft_signs (id, label, image_paths, alt, description)
  select id, label, image_paths, alt, description from app.signs;

  insert into app.draft_exercise_signs (exercise_id, sign_id)
  select exercise_id, sign_id from app.exercise_signs;

  insert into app.draft_study_groups (id, title, position)
  select id, title, position from app.study_groups;

  insert into app.draft_studies (id, group_id, position, title, description, pages)
  select id, group_id, position, title, description, pages from app.studies;
end
$$;
`;
