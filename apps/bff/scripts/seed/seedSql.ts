import type { SeedContent } from './content';

export const SEED_FILE = new URL('../../../../supabase/seed.sql', import.meta.url);

const literal = (value: string) => `'${value.replaceAll("'", "''")}'`;
const nullableLiteral = (value: string | null) => (value === null ? 'null' : literal(value));
const textArray = (values: readonly string[]) => `array[${values.map(literal).join(', ')}]`;
const jsonb = (value: unknown) => `${literal(JSON.stringify(value))}::jsonb`;

function insert(table: string, columns: readonly string[], rows: readonly string[][]): string {
  const values = rows.map((row) => `    (${row.join(', ')})`).join(',\n');
  return `  insert into app.${table} (${columns.join(', ')}) values\n${values};`;
}

// The content belongs to the CMS operators: they edit the tables the app reads. So the seed
// only fills a database without content (a fresh environment) and never runs again over
// what they created, edited, hid or deleted. The seeded content starts visible.
export function renderSeedSql(content: SeedContent): string {
  const { course, units, lessons, signs, exercises, studyGroups, studies } = content;

  const statements = [
    insert(
      'courses',
      ['id', 'title', 'position', 'visible'],
      [[literal(course.id), literal(course.title), String(course.position), 'true']],
    ),
    insert(
      'units',
      ['id', 'course_id', 'title', 'position', 'visible'],
      units.map((unit) => [
        literal(unit.id),
        literal(unit.courseId),
        literal(unit.title),
        String(unit.position),
        'true',
      ]),
    ),
    insert(
      'lessons',
      ['id', 'unit_id', 'title', 'position', 'visible'],
      lessons.map((lesson) => [
        literal(lesson.id),
        literal(lesson.unitId),
        literal(lesson.title),
        String(lesson.position),
        'true',
      ]),
    ),
    insert(
      'signs',
      ['id', 'label', 'image_paths', 'alt', 'description'],
      signs.map((sign) => [
        literal(sign.id),
        literal(sign.label),
        textArray(sign.imagePaths),
        literal(sign.alt),
        nullableLiteral(sign.description),
      ]),
    ),
    insert(
      'exercises',
      ['id', 'lesson_id', 'type', 'position', 'payload'],
      exercises.map(({ lessonId, position, payload }) => [
        literal(payload.id),
        literal(lessonId),
        literal(payload.type),
        String(position),
        jsonb(payload),
      ]),
    ),
    insert(
      'exercise_signs',
      ['exercise_id', 'sign_id'],
      exercises.flatMap(({ payload, signIds }) =>
        signIds.map((signId) => [literal(payload.id), literal(signId)]),
      ),
    ),
    insert(
      'study_groups',
      ['id', 'title', 'position'],
      studyGroups.map((group) => [literal(group.id), literal(group.title), String(group.position)]),
    ),
    insert(
      'studies',
      ['id', 'group_id', 'position', 'title', 'description', 'pages', 'visible'],
      studies.map((study) => [
        literal(study.id),
        literal(study.groupId),
        String(study.position),
        literal(study.title),
        literal(study.description),
        jsonb(study.pages),
        'true',
      ]),
    ),
  ];

  return `-- Generated by apps/bff/scripts/seed/generateSeed.ts. Do not edit by hand:
-- change scripts/seed/content.ts and run \`pnpm --filter bff db:seed:generate\`.
--
-- Fills only a database without content: once there is any, it belongs to the CMS.
do $seed$
begin
  if exists (select 1 from app.courses)
    or exists (select 1 from app.signs)
    or exists (select 1 from app.study_groups) then
    return;
  end if;

${statements.join('\n\n')}
end
$seed$;
`;
}
